    private void cargaListaEnTabla(LinkedList<DeltaMatroide> A, DefaultTableModel ModeloTablaA) {
         ModeloTablaA.setRowCount(0);
        for (int i = 0; i < A.size(); i++) {
            DeltaMatroide get = A.get(i);
                get.setModeFactibles0();
                String renglon[] = {(i + 1) + "", get.getNombreFam(), get.getResultado()};
                ModeloTablaA.addRow(renglon);

            }

        }
