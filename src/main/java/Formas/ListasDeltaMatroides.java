    private void cargaFolderEnTablaAdm(ElementoFolder aux) {
        
       TablaAdmi.setRowCount(0);
        folderAdmin=aux;
        for (int i = 0; i < folderAdmin.folder.size(); i++) {
            ElementoFolder get = folderAdmin.folder.get(i);
            String conte="",nombre;
            if(get.isIsFolder()) {
                conte="Carpeta";
                nombre=get.getNombre();
            }
            else {
                get.getMatrode().setModeFactibles0();
                conte=get.getMatrode().getResultado();
                nombre=get.getMatrode().getNombreFam();
                }
                Object renglon[] = {false,i + 1, nombre,conte };
                TablaAdmi.addRow(renglon);

            

        }
       
    }

