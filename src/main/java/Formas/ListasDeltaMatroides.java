    private void jButton7ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton7ActionPerformed
        // TODO add your handling code here:
        if(resultado.size()>0){
         Main.ventanaSelector= new SelectorMatroide(this, true, 5);
        Main.ventanaSelector.setVisible(true);
        ElementoFolder F= (ElementoFolder) Main.pila.pop();
        String[] botones={"Combinar contenidos","Crear una Subcarpeta"};
        int variable = JOptionPane.showOptionDialog (null, "¿Deseas guardar todos los delta-matroides en esta carpeta y \ncombinar su contenido o "
                + "crear una nueva subcarpeta?", "Combinar o subcarpeta", JOptionPane.YES_NO_OPTION, JOptionPane.QUESTION_MESSAGE, null/*icono*/, botones, botones[0]);
        switch(variable){
            case 0: 
                for(DeltaMatroide D:resultado){
                    ElementoFolder fi=new ElementoFolder(false,D.getNombreFam(),D, F);
                    F.folder.add(fi);
                }
            break;
            case 1:
                String nombre = JOptionPane.showInputDialog(
                        this,"Nombre de la nueva carpeta ", JOptionPane.INFORMATION_MESSAGE);
                ElementoFolder folder=new ElementoFolder(true, nombre, new LinkedList<ElementoFolder>(), F);
                for(DeltaMatroide D:resultado){
                    ElementoFolder fi=new ElementoFolder(false,D.getNombreFam(),D, folder);
                    folder.folder.add(fi);
                }
                F.folder.add(folder);
            break;
        }
        }else JOptionPane.showMessageDialog(this,"No hay elementos en la lista de resultado\npara guardar.");
    }//GEN-LAST:event_jButton7ActionPerformed

