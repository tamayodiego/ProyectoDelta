    private void llenaListaSeleccionada(LinkedList<ElementoFolder> lista) {
        modeloTabla.setRowCount(0);
        listaDeltaMatroides.clear();
        for (int i = 0; i < lista.size(); i++) {
            ElementoFolder get = lista.get(i);
            if (!get.isIsFolder()) {
                DeltaMatroide aux = get.getMatrode();
                listaDeltaMatroides.add(aux);
                aux.setModeFactibles0();
                String renglon[] = {(i + 1) + "", aux.getNombreFam(), aux.getResultado()};
                modeloTabla.addRow(renglon);

            }

        }
        // listaDeIsomorfismo.setModel(modelo);
    }

    private String imprimeFuncionBi(LinkedList<String[]> funcionBi) {
        String cad = "";
        for (int i = 0; i < funcionBi.get(0).length; i++) {
            cad += funcionBi.get(0)[i] + "-------" + funcionBi.get(1)[i] + "\n";
        }

        return cad;
    }

