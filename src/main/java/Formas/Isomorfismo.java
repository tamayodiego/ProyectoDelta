    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        try {
            // TODO add your handling code here:
            if(jTextArea3.getText().equals("") || jTextArea4.getText().equals("")) throw new NoEntradaValida("falta uno o mas DeltaMatroides en la entrada");
            if (!DMCargado1) {
                ConstructorFamilias con1 = new ConstructorFamilias(jTextArea3.getText().split("=")[1]);
                D1 = new DeltaMatroide(con1.getFamilia(), jTextArea3.getText().split("=")[0], con1.getConjuntoV());
            }
            if (!DMCargado2) {

                ConstructorFamilias con2 = new ConstructorFamilias(jTextArea4.getText().split("=")[1]);
                D2 = new DeltaMatroide(con2.getFamilia(), jTextArea4.getText().split("=")[0], con2.getConjuntoV());
            }

            LinkedList<String[]> funcionBi = D1.isIsomorfo(D2);
            if (funcionBi != null) {
                jTextArea5.setText(D1.getNombreFam() + " y " + D2.getNombreFam() + " son isomorfos: \n"
                        + imprimeFuncionBi(funcionBi));
            } else {
                jTextArea5.setText("No son isomorfos");
            }

        } catch (NoEntradaValida ex) {
            JOptionPane.showMessageDialog(null, ex.getMessage(), "Error", JOptionPane.WARNING_MESSAGE);
        }

    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        try {
            // TODO add your handling code here:
            int cont=0;
            if(renglones==null) throw new NoEntradaValida("No has cargado ninguna lista");
            for (int i = 0; i < renglones.length; i++) {
                renglones[i] = false;
            }
            funcionesBiyectivas.clear();
            if(DMCargadoB){
                if(jTextArea1.getText().equals("")) throw new NoEntradaValida("No has introducido un DeltaMatroide Valido");
                
                ConstructorFamilias con = new ConstructorFamilias(jTextArea1.getText());
                String[] A=jTextArea1.getText().split("=");
                matroide = new DeltaMatroide(con.getFamilia(), A[0], con.getConjuntoV());
            }
            for (int i = 0; i < listaDeltaMatroides.size(); i++) {
                DeltaMatroide get = listaDeltaMatroides.get(i);
                LinkedList<String[]> funcion = matroide.isIsomorfo(get);
                funcionesBiyectivas.add(funcion);
                if (funcion != null) {
                    renglones[i] = true;
                    cont++;
                }

            }

            jTable1.setDefaultRenderer(Object.class, new MiRender2(fila -> renglones[fila]));

            jTable1.repaint();
            // jTable1.setVisible(true);
            // jScrollPane8.setVisible(true);

            String cad = "" + cont+ " DeltaMatroides son Isomorfos:\n";
            jTextArea2.setText(cad);
            resultadoListo=true;

        } catch (NoEntradaValida ex) {
            
           JOptionPane.showMessageDialog(null, ex.getMessage(), "Error", JOptionPane.WARNING_MESSAGE);
        } catch (Exception ex) {
            Logger.getLogger(Isomorfismo.class.getName()).log(Level.SEVERE, null, ex);
        } 
    }//GEN-LAST:event_jButton2ActionPerformed

