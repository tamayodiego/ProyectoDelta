    public String generaMatrisString(byte [][] mat, boolean modoEtiquetas){
        String cadena="";
        if(!modoEtiquetas){

            cadena+="   ";
            String aux[]=this.matroide.getEtiquetas();
            for(int i =0;i<mat.length;i++) cadena+=aux[listaEnteros.get(i)]+"   ";
            cadena+="\n";
            
            for(int i =0;i<mat.length;i++){
               cadena+=aux[listaEnteros.get(i)]+"  ";
               for(int j =0 ;j<mat.length;j++){
                   cadena+=mat[i][j];
                   if(j!=mat.length-1) cadena+="  ";
                }
               cadena+="\n";
            }
        }
        else{
            cadena+="     ";
            String aux[]=this.matroide.getEtiquetas();
            for(int i =0;i<mat.length;i++){ cadena+=aux[i];
                if(aux[i].length()==1) cadena+="   ";
                else cadena+="  ";
            }
            cadena+="\n";
            
            for(int i =0;i<mat.length;i++){
               cadena+=aux[i];
               if(aux[i].length()==1) cadena+="   ";
                else cadena+="  "; 
               for(int j =0 ;j<mat.length;j++){
                   cadena+=mat[i][j];
                   if(j!=mat.length-1) {
                       if(aux[i].length()==1) cadena+="   ";
                        else cadena+="  ";
                   }
                }
               cadena+="\n";
             }
            
            
        }
        return cadena;
        
    }
