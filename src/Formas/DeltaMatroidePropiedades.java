    private void cargaSubMatrizEnTabla(GraperFactible g){
       byte [][] m=(new Generador()).generarMatriz(g.getFactible(),matroide.getM());
        String Columnas[]=new String [m.length +1];
        Columnas[0]="";
        for (int i = 1; i < Columnas.length; i++) {
            Columnas[i]=matroide.getEtiquetas()[g.getFactible().get(i-1)];
            
        }
        
        String datos[][]=new String[m.length][m.length+1];
        LinkedList<Integer> aux1=g.getFactible();
        LinkedList<Integer> aux2=g.getFactible();
        for (int i = 0; i < m.length; i++) {
            datos[i][0]=matroide.getEtiquetas()[g.getFactible().get(i)];
            for (int j = 1; j <=m.length; j++) {
                datos[i][j]=m[i][j-1]+"";
                celdas[aux1.get(i)][1+aux1.get(j-1)]=true;
              //  System.out.println(celdas[aux1.get(i)][1+aux1.get(j-1)]);
            }
        }
        cargaMatriz();
        DefaultTableModel tm = new DefaultTableModel(datos, Columnas) {
            @Override
            public boolean isCellEditable(int row, int column) {
                    if (0 == column)
                            return false;
                    return super.isCellEditable(row, column);
            }
        };
        tabla2 = new JTableImpl(tm);
      tabla2.getColumnModel().getColumn(0).setCellRenderer(tabla.getTableHeader().getDefaultRenderer());
      tabla2.setVisible(true);
      jScrollPane4.setViewportView(tabla2);
      
      
        
      
    }
    
    
    private void cargaMatrizEnTabla(byte[][] m) {
        String Columnas[]=new String [m.length+1];
        Columnas[0]="";
        for (int i = 1; i < Columnas.length; i++) {
            Columnas[i]=matroide.getEtiquetas()[i-1];
            
        }
       
        String datos[][]=new String[m.length][m.length+1];
        
        for (int i = 0; i < m.length; i++) {
            datos[i][0]=matroide.getEtiquetas()[i];
            for (int j = 1; j <=m.length; j++) {
                datos[i][j]=m[i][j-1]+"";
                
            }
        }
        DefaultTableModel tm = new DefaultTableModel(datos, Columnas) {
            @Override
            public boolean isCellEditable(int row, int column) {
                    if (0 == column)
                            return false;
                    return super.isCellEditable(row, column);
            }
        };
        tabla = new JTableImpl(tm);
        tabla.setDefaultRenderer (Object.class, new MiRender());
      tabla.getColumnModel().getColumn(0).setCellRenderer(tabla.getTableHeader().getDefaultRenderer());
      tabla.setVisible(true);
      jScrollPane5.setViewportView(tabla);
        
    }

    private void llenaDeFalsos() {
        celdas=new boolean[matroide.getM().length][matroide.getM().length+1];
        for (int i = 0; i < celdas.length; i++) {
            for (int j = 0; j < celdas.length+1; j++) {
                celdas[i][j]=false;
                
            }
            
        }
    }

    private class JTableImpl extends JTable {

        public JTableImpl(TableModel dm) {
            super(dm);
        }

        @Override
        public void changeSelection(int rowIndex, int columnIndex,
                boolean toggle, boolean extend) {
            if (columnIndex == 0)
                // Podemos llamar a changeSelecion() incrementando la columna en 1
                // o bien podríamos hacer directamente un return.
                super.changeSelection(rowIndex, columnIndex + 1, toggle, extend);
            else
                super.changeSelection(rowIndex, columnIndex, toggle, extend);
        }
    }
