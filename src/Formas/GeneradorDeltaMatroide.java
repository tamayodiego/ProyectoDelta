    public String generaMatrisString(byte[][] mat, boolean modoEtiquetas) {
        String cadena = "";
        if (!modoEtiquetas) {

            for (int i = 0; i < mat.length; i++) {
                for (int j = 0; j < mat.length; j++) {
                    cadena += mat[i][j];
                    if (j != mat.length - 1) {
                        cadena += " ";
                    }
                }
                cadena += "\n";
            }
        } else {
            cadena += "    ";
            String aux[] = this.m.getEtiquetas();
            for (int i = 0; i < mat.length; i++) {
                cadena += aux[i] + "  ";
            }
            cadena += "\n";

            for (int i = 0; i < mat.length; i++) {
                cadena += aux[i] + "  ";
                for (int j = 0; j < mat.length; j++) {
                    cadena += mat[i][j] + "  ";
                }
                cadena += "\n";
            }

        }
        return cadena;

    }

