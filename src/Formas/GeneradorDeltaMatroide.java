    private void validaEntradaMatriz(String aux1) throws NumberFormatException {
        for (int i = 0; i < aux1.length(); i++) {
            if (aux1.charAt(i) >= 'A' && aux1.charAt(i) <= 'z') {
                throw new NumberFormatException("Existen Caracteris Invalidos En la Entrada");
            }
        }

    }

    private boolean validaMatriz(byte[][] M) throws ValorFueraDeRangoValido, NoMatrizSimetrica {
        for (int i = 0; i < M.length; i++) {
            for (int j = 0; j < M.length; j++) {
                if (M[i][j] < -1 || M[i][j] > 1) {
                    throw new ValorFueraDeRangoValido(M[i][j] + " no es una Entrada Valida");
                }
            }
        }

        for (int i = 0; i < M.length; i++) {
            for (int j = 0; j < M.length; j++) {

                if (M[i][j] == M[j][i] || M[i][j] == -M[j][i]); else {
                    throw new NoMatrizSimetrica("El Termino en M" + i + "," + j + "="
                            + M[i][j] + " no corresponde a M" + j + "," + i + "=" + M[j][i]);
                }
            }
        }
        return true;
    }
