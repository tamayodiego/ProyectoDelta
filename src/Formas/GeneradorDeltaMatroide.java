    private byte[][] obtenMatrizTeclado() throws FaltanMiniTerminos, NoEntradaValida {

        String aux1 = TextoMatriz.getText();
        if(aux1.equals("")) throw new NoEntradaValida("Sin Datos de entrada");
        System.out.println(aux1);
        validaEntradaMatriz(aux1);
        AlmacenEnteros parser = new AlmacenEnteros(aux1);
        
        int n = parser.nextInt();
        if(n<0) throw new NoEntradaValida("Entrada invalida");
        byte[][] M = new byte[n][n];
        System.out.println(n);

        for (int i = 0; i < n; i++) {

            for (int j = 0; j < n; j++) {
                M[i][j] = (byte) parser.nextInt();
                if (M[i][j] == -2) {
                    throw new FaltanMiniTerminos("Faltan Entradas de la matriz de adyacenca. Solo se lograron leer "
                            + ((i * n) + j) + " de los " + (n * n) + " Entradas");
                }
            }

        }
        return M;

    }

    private byte[][] obtenMatrizArchivo() {

        String aux1 = TextoMatriz.getText();
        String[] aux2 = aux1.split("\n");
        int n = Integer.parseInt(aux2[0]);
        byte[][] M = new byte[n][n];
        System.out.println(n);

        for (int i = 0; i < n; i++) {
            String[] aux3 = aux2[i + 1].split(" ");
            for (int j = 0; j < n; j++) {
                M[i][j] = Byte.parseByte(aux3[j]);
            }

        }
        return M;
    }

