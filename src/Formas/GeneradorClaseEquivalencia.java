    private void calculaClaseDeEquivalencia() {
        LinkedList< LinkedList<Integer> > conjuntoPotencia;
        if(modoNormales)conjuntoPotencia=DM.getFamilia();
        else conjuntoPotencia=generaConjuntoPotencia(DM.cardiConjuntoV);
        LinkedList<DeltaMatroide> deltaEquivalentes=new LinkedList<>();
        for (LinkedList<Integer> factible : conjuntoPotencia) {
            DeltaMatroide D=(DeltaMatroide) DM.clone();
            D.twist(factible);
            String nombre=D.getNombreFam()+"Δ"+"{";
            for (int i = 0; i < factible.size(); i++) {
                nombre+=D.getEtiquetas()[factible.get(i)]+"";
                if(i != (factible.size()-1)) nombre+=",";
            }
            nombre+="}";
            D.setNombreFam(nombre);
            System.out.println(D.getNombreFam());
            deltaEquivalentes.add(D);
        }
        if(modoNoIsomorfos) cargaEnLista((new OperacionesListas()).depuracionIsomorfica(deltaEquivalentes));
        else cargaEnLista(deltaEquivalentes);
       
    }

