    void construye(boolean[] arr, int  ite,int n,LinkedList<LinkedList<Integer>> Pv ){
    if(ite==n){
        LinkedList<Integer> aux=new LinkedList<>();
        for(int i=0;i< arr.length; i++) if(arr[i]) aux.add(i);
        Pv.add(aux);
    }else{
        arr[ite]=true;
        construye(arr,ite+1,n,Pv);
        arr[ite]=false;
        construye(arr,ite+1,n,Pv);
    }
}

    private LinkedList<LinkedList<Integer>> generaConjuntoPotencia(int cardiConjuntoV) {
      LinkedList< LinkedList<Integer> > conjuntoPotencia=new LinkedList<>();
      construye(new boolean[cardiConjuntoV],0,cardiConjuntoV,conjuntoPotencia);
      return conjuntoPotencia;
    }
